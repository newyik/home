import { dateDaysAgo, isoDaysAgo } from './dates';
import { prefectureFor } from './prefectures';
import type { RoadtripPlace } from './types';

function makePlace(
  base: Omit<
    RoadtripPlace,
    'prefectureName' | 'region' | 'createdAt' | 'updatedAt' | 'createdByName' | 'visitedByName'
  > & {
    prefectureName?: string;
    region?: RoadtripPlace['region'];
    createdAt?: string;
    updatedAt?: string;
    createdByName?: string;
    visitedByName?: string | null;
  },
): RoadtripPlace {
  const prefecture = prefectureFor(base.prefectureCode);
  const createdAt = base.createdAt ?? isoDaysAgo(30);
  return {
    ...base,
    prefectureName: base.prefectureName ?? prefecture.name,
    region: base.region ?? prefecture.region,
    createdByName: base.createdByName ?? '小雨',
    visitedByName: base.visitedByName ?? (base.status === 'visited' ? '阿哲' : null),
    createdAt,
    updatedAt: base.updatedAt ?? createdAt,
  };
}


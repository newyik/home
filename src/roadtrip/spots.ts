export const JAPAN_SPOTS: JapanSpot[] = ROWS.map(([id, name, nameJa, prefectureCode, lat, lng, category]) => ({
  id,
  name,
  nameJa,
  aliases: [prefectureFor(prefectureCode).name, prefectureFor(prefectureCode).nameJa],
  prefectureCode,
  lat,
  lng,
  category,
}));

export function searchJapanSpots(queryText: string, limit = 8): JapanSpot[] {
  const query = queryText.trim().toLowerCase();
  if (!query) return [];
  return JAPAN_SPOTS.filter((spot) =>
    [spot.name, spot.nameJa, ROADTRIP_CATEGORY_MAP[spot.category].label, ...spot.aliases]
      .join(' ')
      .toLowerCase()
      .includes(query),
  ).slice(0, limit);
}

export function spotById(id: string): JapanSpot | undefined {
  return JAPAN_SPOTS.find((spot) => spot.id === id);
}

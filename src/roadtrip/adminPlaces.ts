function stripSuffix(name: string): string {
  return name.replace(/[都道府県县府市町村]$/g, '');
}

function compactAliases(values: Array<string | undefined>): string[] {
  return Array.from(new Set(values.filter((value): value is string => Boolean(value && value.trim()))));
}

const prefecturePlaces: AdminPlace[] = PREFECTURES.map((prefecture) => {
  const short = stripSuffix(prefecture.name);
  const shortJa = stripSuffix(prefecture.nameJa);
  return {
    id: `pref-${prefecture.code}`,
    name: prefecture.name,
    nameJa: prefecture.nameJa,
    aliases: compactAliases([short, shortJa, ...(PREFECTURE_EN[prefecture.code] ?? [])]),
    prefectureCode: prefecture.code,
    lat: prefecture.lat,
    lng: prefecture.lng,
    category: 'city',
    kind: 'prefecture',
  };
});

const capitalPlaces: AdminPlace[] = PREFECTURES.flatMap((prefecture) => {
  const capital = CAPITALS[prefecture.code];
  if (!capital) return [];
  const [name, nameJa] = capital;
  return [{
    id: `city-${prefecture.code}`,
    name,
    nameJa,
    aliases: compactAliases([stripSuffix(name), stripSuffix(nameJa)]),
    prefectureCode: prefecture.code,
    lat: prefecture.lat,
    lng: prefecture.lng,
    category: 'city' as const,
    kind: 'city' as const,
  }];
});


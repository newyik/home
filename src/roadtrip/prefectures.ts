export const PREFECTURES: Prefecture[] = ROWS.map(([code, name, nameJa, region, lat, lng]) => ({
  code,
  name,
  nameJa,
  region,
  lat,
  lng,
}));

export const PREFECTURE_MAP: Record<string, Prefecture> = Object.fromEntries(
  PREFECTURES.map((prefecture) => [prefecture.code, prefecture]),
);

export function prefectureFor(code: string): Prefecture {
  return PREFECTURE_MAP[code] ?? PREFECTURE_MAP['13'];
}

export function nearestPrefecture(lat: number, lng: number): Prefecture {
  let best = PREFECTURES[0];
  let bestDistance = Number.POSITIVE_INFINITY;

  for (const prefecture of PREFECTURES) {
    const latScale = Math.cos((lat * Math.PI) / 180);
    const dLat = lat - prefecture.lat;
    const dLng = (lng - prefecture.lng) * latScale;
    const distance = dLat * dLat + dLng * dLng;
    if (distance < bestDistance) {
      bestDistance = distance;
      best = prefecture;
    }
  }

  return best;
}

export function prefectureLabel(code: string): string {
  return prefectureFor(code).name;
}
